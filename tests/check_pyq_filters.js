'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const rules=require('../docs/assets/pyq-filters.js');
const papers=JSON.parse(fs.readFileSync(path.join(__dirname,'../docs/data/library.json'),'utf8')).pyqs;
const bySession=rules.sessions(papers,'5');
assert.deepEqual(bySession,['November 2025','December 2022','January 2021','December 2020','November 2019']);
assert.deepEqual(rules.subjects(papers,'5','November 2025').map(s=>s.key),['industrial-pharmacy-1']);
assert.equal(rules.subjects(papers,'5','December 2022').length,5);
assert.equal(rules.subjects(papers,'5','January 2021').length,4);
assert.ok(!rules.subjects(papers,'5','January 2021').some(s=>s.key==='medicinal-chemistry-2'));
let f=rules.normalize(papers,{semester:'5',session:'December 2022',subject:'medicinal-chemistry-2'});
assert.equal(rules.filter(papers,f).length,1);
f=rules.normalize(papers,{...f,session:'November 2025'});
assert.equal(f.subject,'all');
assert.equal(rules.filter(papers,f)[0].code,'76787');
f=rules.normalize(papers,{...f,semester:'2'});
assert.deepEqual([f.session,f.subject],['all','all']);
assert.equal(rules.filter(papers,f).length,37);
assert.deepEqual(rules.sessions(papers,'2'),['May 2026','December 2022','December 2020','March 2020','November 2019','May 2019','December 2018']);
f=rules.normalize(papers,{semester:'5',subject:'pharmaceutical-jurisprudence',query:'2022'});
assert.equal(rules.filter(papers,f).length,1);
assert.equal(rules.filter(papers,f)[0].session,'December 2022');
assert.deepEqual(rules.sessions(papers,'6'),['May 2026','January 2023','December 2020']);
assert.equal(rules.subjects(papers,'6','May 2026').length,2);
assert.equal(rules.subjects(papers,'6','January 2023').length,6);
f=rules.normalize(papers,{semester:'6',session:'January 2023',subject:'medicinal-chemistry-3'});
assert.equal(rules.filter(papers,f).length,1);
f=rules.normalize(papers,{...f,session:'May 2026'});
assert.equal(f.subject,'all');
assert.equal(rules.filter(papers,f).length,2);
assert.equal(rules.subjects(papers,'7','December 2022').length,4);
assert.equal(rules.subjects(papers,'8','January 2023').length,10);
f=rules.normalize(papers,{semester:'8',session:'December 2022',subject:'cosmetic-science'});
assert.equal(f.subject,'all');
assert.equal(rules.filter(papers,f)[0].syllabusSubject,'biostatistics-and-research-methodology');
console.log('Session availability, subject availability, dependent resets, and combined filters passed.');
